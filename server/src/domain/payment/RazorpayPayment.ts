import crypto from 'crypto';
import { PaymentMethod } from './PaymentMethod';
import { PaymentResult, PaymentReceipt } from './PaymentResult';
import { ValidationError } from '../../errors';

/** OOP: Polymorphism, Abstraction & Encapsulation
 *  WHY: Integrates Razorpay payment gateway polymorphically as an IPaymentMethod, encapsulating order binding, HMAC-SHA256 signature verification, and standardizing audit receipts. */
export class RazorpayPayment extends PaymentMethod {
  // ENCAPSULATION: Razorpay credentials and telemetry parameters are private
  private _orderId: string | null = null;
  private _paymentId: string | null = null;
  private _signature: string | null = null;
  private _isVerified: boolean = false;

  constructor(orderId?: string, paymentId?: string, signature?: string) {
    super();
    if (orderId) this._orderId = orderId;
    if (paymentId) this._paymentId = paymentId;
    if (signature) this._signature = signature;
  }

  // ABSTRACTION: Concrete implementation of getMethodName contract
  public getMethodName(): string {
    return 'RAZORPAY';
  }

  // ENCAPSULATION: Setters validate and bind Razorpay gateway metadata
  public bindOrder(orderId: string, paymentId?: string): void {
    if (!orderId || !orderId.trim()) {
      throw new ValidationError('Valid Razorpay order ID is required');
    }
    this._orderId = orderId.trim();
    if (paymentId && paymentId.trim()) {
      this._paymentId = paymentId.trim();
    }
  }

  public setVerification(paymentId: string, signature: string): void {
    if (!paymentId || !signature) {
      throw new ValidationError('Payment ID and Signature are required for Razorpay verification');
    }
    this._paymentId = paymentId.trim();
    this._signature = signature.trim();
    this._isVerified = true;
  }

  /**
   * ENCAPSULATION: Verifies HMAC SHA-256 signature generated by Razorpay Checkout
   * signature = hmac_sha256(order_id + "|" + payment_id, key_secret)
   * Supports either:
   *   verifySignature(signature, secret) - using bound orderId & paymentId
   *   verifySignature(orderId, paymentId, signature, secret) - using provided IDs
   */
  public verifySignature(
    signatureOrOrderId: string,
    secretOrPaymentId: string,
    maybeSignature?: string,
    maybeSecret?: string
  ): boolean {
    let orderId = this._orderId;
    let paymentId = this._paymentId;
    let signature = signatureOrOrderId;
    let secret = secretOrPaymentId;

    if (maybeSignature !== undefined && maybeSecret !== undefined) {
      orderId = signatureOrOrderId;
      paymentId = secretOrPaymentId;
      signature = maybeSignature;
      secret = maybeSecret;
    }

    if (!orderId || !paymentId) {
      throw new ValidationError('Cannot verify signature without orderId and paymentId');
    }
    if (!signature || !secret) {
      return false;
    }

    try {
      const generatedSignature = crypto
        .createHmac('sha256', secret)
        .update(`${orderId}|${paymentId}`)
        .digest('hex');

      const isMatch = crypto.timingSafeEqual(
        Buffer.from(generatedSignature),
        Buffer.from(signature)
      );

      if (isMatch) {
        this._orderId = orderId;
        this._paymentId = paymentId;
        this._signature = signature;
        this._isVerified = true;
      }

      return isMatch;
    } catch {
      return false;
    }
  }

  // POLYMORPHISM: Specialized asynchronous settlement logic for Razorpay Gateway
  public async pay(amount: number): Promise<PaymentResult> {
    if (amount <= 0) {
      throw new ValidationError('Payment amount must be greater than zero');
    }

    const txnId = this._paymentId || this.generateTransactionId('pay_rzp');
    this._lastTransactionId = txnId;

    const result: PaymentResult = {
      success: true,
      status: 'COMPLETED',
      transactionId: txnId,
      amount,
      timestamp: new Date(),
      message: `Razorpay Payment captured successfully (Order: ${this._orderId || 'DIRECT'}, Payment: ${txnId})`
    };

    this._lastResult = result;
    return result;
  }

  // INHERITANCE & POLYMORPHISM: Extends base receipt with Razorpay audit tokens
  public override receipt(): PaymentReceipt & { orderId?: string | null; paymentId?: string | null } {
    const base = super.receipt();
    return {
      ...base,
      orderId: this._orderId,
      paymentId: this._paymentId,
      details: `${base.details} • Verified: ${this._isVerified ? 'YES' : 'PENDING'} • Order: ${this._orderId || 'N/A'}`
    };
  }

  public getOrderId(): string | null {
    return this._orderId;
  }

  public getPaymentId(): string | null {
    return this._paymentId;
  }

  public getSignature(): string | null {
    return this._signature;
  }

  public isVerified(): boolean {
    return this._isVerified;
  }
}
